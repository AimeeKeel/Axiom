type Shapes = {
  conformance: Map<string, string>;
  missing: Map<string, string[]>;
  members: Map<string, Member[]>;
  returns: Map<string, string>;
  cases: Map<string, string[]>;
  unions: Map<string, string[]>;
  statics: Map<string, string[]>;
  warnings: Map<string, string[]>;
};

type CensusRun = {
  dir: string;
  decls: SchemaDecl[];
  ids: Map<string, string>;
  byAccessor: Map<string, SchemaDecl>;
  shapes: Shapes;
  /** First domain whose schemas name each union; its probe type is `U_<domain>_<union>`. */
  unionOwner: Map<string, string>;
};

const push = <T>(map: Map<string, T[]>, k: string, v: T) => map.set(k, [...(map.get(k) ?? []), v]);
const stubFor = (c: CensusRun, d: SchemaDecl) => STUBS[c.shapes.conformance.get(key(d)) ?? ""];
const membersOf = (c: CensusRun, k: string) => (c.shapes.members.get(k) ?? []).slice().sort((a, b) => byCode(a.name, b.name));

function run(command: string, args: string[], cwd?: string): string {
  const result = spawnSync(command, args, { cwd, encoding: "utf8" });
  if (result.status !== 0) throw new Error(`${command} ${args.join(" ")} failed: ${result.stderr || result.stdout}`);
  return result.stdout.trim();
}

function build(dir: string, source: Source, label: string): BuildResult {
  fs.writeFileSync(path.join(dir, "Probe/All.swift"), source.text);
  const logPath = path.join(dir, `${label}.log`);
  const fd = fs.openSync(logPath, "w");
  spawnSync(
    "xcodebuild",
    ["-project", "Census.xcodeproj", "-scheme", "Census", "-destination", "generic/platform=iOS",
      "-derivedDataPath", path.join(dir, "dd"), "ARCHS=arm64", "build"],
    { cwd: dir, stdio: ["ignore", fd, fd] },
  );
  fs.closeSync(fd);
  const log = fs.readFileSync(logPath, "utf8");
  const succeeded = log.includes("** BUILD SUCCEEDED **");
  if (!succeeded && !log.includes("** BUILD FAILED **")) {
    throw new Error(`${label}: xcodebuild ended without a build result; see ${logPath}`);
  }
  console.log(`  ${label}: ${succeeded ? "succeeded" : "failed"}, log at ${logPath}`);
  const diagnostics = parseDiagnostics(log);
  if (label !== "pass1" && diagnostics.swift.length > 0) {
    throw new Error(`${label}: the probe did not compile, so the processor never ran:\n  ${diagnostics.swift.slice(0, 15).join("\n  ")}`);
  }
  return { ...diagnostics, succeeded };
}

type Visit = (owner: string, kind: MetadataKind, message: string, finding: Finding | undefined) => boolean;

/** The schema a diagnostic belongs to: by line, or by the schema a location-less error names. */
function diagnosticOwner(source: Source, d: Diagnostics["metadata"][number]): string | undefined {
  const named = /Schema(Intent|Entity|Enum) '(\w+)\.(\w+)'/.exec(d.message);
  return d.line === 0 && named ? `${named[2]}.${named[1].toLowerCase()}.${named[3]}` : ownerOf(source, d.line);
}

/** Calls `visit` per diagnostic with its owning schema; prints what neither it nor the classifier recognized. */
function eachMetadata(source: Source, diagnostics: Diagnostics, label: string, visit: Visit) {
  for (const d of diagnostics.metadata) {
    const finding = d.kind === "error" ? classifyMetadata(d.message) : undefined;
    const owner = diagnosticOwner(source, d);
    if (!owner || !visit(owner, d.kind, d.message, finding)) console.log(`  ${label}: unrecognized: ${owner ?? `line ${d.line}`}: ${d.message}`);
  }
}

/** Pass 1: Swift names the protocols each schema macro adds. */
function conformances(c: CensusRun): void {
  const source = assemble(c.decls.map((d) => ({
    key: key(d),
    text: d.kind === "intent" ? intentText(d, [], [], undefined) : d.kind === "entity" ? entityText(d, undefined, [], false) : enumText(d, []),
  })));
  const result = build(c.dir, source, "pass1");
  const byStruct = new Map(c.decls.map((d) => [structName(d), d]));
  for (const message of result.swift) {
    const m = /^type '(\w+)' does not conform to protocol '(\w+)'$/.exec(message);
    if (m && byStruct.has(m[1])) c.shapes.conformance.set(key(byStruct.get(m[1])!), m[2]);
    else if (!/does not conform to protocol|requires the types .* be equivalent/.test(message)) {
      throw new Error(`pass1: unexpected Swift error: ${message}`);
    }
  }
  for (const [k, protocol] of c.shapes.conformance) {
    if (k.includes(".intent.") && !STUBS[protocol]) throw new Error(`pass1: ${k} conforms to ${protocol}; add a stub to STUBS`);
  }
}

/** Pass 2: the processor names required members, cases and return types; entity fix-its give property types. */
function requiredMembers(c: CensusRun): string[] {
  const source = assemble(c.decls.map((d) => {
    const s = stubFor(c, d);
    const text = d.kind === "intent"
      ? intentText(d, s?.members ?? [], (s?.parameters ?? []).map((p) => `@Parameter var ${p.name}: ${p.type}`), undefined)
      : d.kind === "entity" ? entityText(d, c.shapes.conformance.get(key(d)), [], false) : enumText(d, []);
    return { key: key(d), text };
  }));
  const result = build(c.dir, source, "pass2");
  if (!result.metadata.some((d) => classifyMetadata(d.message)?.kind === "missing")) {
    throw new Error("pass2: the processor reported no missing members, so the probe never reached it; the census would be empty");
  }
  const fixits = new Map<string, Map<string, string>>();
  eachMetadata(source, result, "pass2", (owner, kind, message, finding) => {
    if (kind === "warning") return true;
    if (kind === "fixit") {
      const m = /^var (\w+): (.+)$/.exec(message);
      if (m) fixits.set(owner, (fixits.get(owner) ?? new Map()).set(m[1], m[2]));
      return Boolean(m);
    }
    if (finding?.kind === "missing") push(c.shapes.missing, owner, finding.name);
    else if (finding?.kind === "case") push(c.shapes.cases, owner, finding.name);
    else if (finding?.kind === "returns") c.shapes.returns.set(owner, processorType(finding.type, c.ids, c.shapes.unions));
    return finding !== undefined;
  });
  // Entity properties whose fix-it names a type that is neither Swift nor a schema (a union) get typed in pass 3.
  const opaque: string[] = [];
  for (const d of c.decls.filter((d) => d.kind === "entity")) {
    const k = key(d);
    for (const name of unique(c.shapes.missing.get(k) ?? [])) {
      const raw = fixits.get(k)?.get(name);
      if (!raw) throw new Error(`pass2: ${k} requires property ${name} but no fix-it gave its type`);
      const t = fixitType(raw, c.ids);
      push(c.shapes.members, k, { name, ...t });
      const bare = t.type.replace(/^\[(.*)\]$/, "$1");
      if (/^[A-Z]\w*$/.test(bare) && !c.ids.has(bare) && !SWIFT_TYPES.has(bare)) opaque.push(`${k}#${name}`);
    }
  }
  return opaque;
}

const SWIFT_TYPES = new Set(["String", "Bool", "Int", "Double", "Date", "URL", "Duration", "AttributedString", "DateComponents", "IntentFile", "IntentPerson"]);

/** Pass 3: wrong-typed members make the processor print the type it wanted, and whether it must be optional. */
function memberTypes(c: CensusRun, opaque: string[]): void {
  const source = assemble(c.decls.map((d) => {
    const k = key(d);
    const s = stubFor(c, d);
    if (d.kind === "intent") {
      const parameters = [
        ...(s?.parameters ?? []).map((p) => `@Parameter var ${p.name}: ${p.type}`),
        ...unique(c.shapes.missing.get(k) ?? []).map((n) => `@Parameter var ${n}: ProbeEntity`),
      ];
      return { key: k, text: intentText(d, s?.members ?? [], parameters, undefined) };
    }
    if (d.kind === "entity") {
      const properties = opaque.filter((o) => o.startsWith(`${k}#`)).map((o) => `var ${o.split("#")[1]}: ProbeEntity`);
      return { key: k, text: entityText(d, c.shapes.conformance.get(k), properties, false) };
    }
    return { key: k, text: enumText(d, []) };
  }));
  const result = build(c.dir, source, "pass3");
  const types = new Map<string, Map<string, string>>();
  const optionals = new Map<string, Set<string>>();
  eachMetadata(source, result, "pass3", (owner, kind, _message, finding) => {
    if (kind !== "error") return true;
    if (finding?.kind === "type") types.set(owner, (types.get(owner) ?? new Map()).set(finding.name, finding.type));
    else if (finding?.kind === "optionality" && finding.optional) optionals.set(owner, (optionals.get(owner) ?? new Set()).add(finding.name));
    return finding !== undefined;
  });
  for (const d of c.decls) {
    const k = key(d);
    if (d.kind === "intent") {
      const stubs = stubFor(c, d)?.parameters ?? [];
      for (const name of unique([...stubs.map((p) => p.name), ...(c.shapes.missing.get(k) ?? [])])) {
        const raw = types.get(k)?.get(name);
        const declared = stubs.find((p) => p.name === name)?.type ?? "ProbeEntity";
        // No mismatch for a ProbeEntity: the processor accepted an entity that adopts no schema.
        let type = raw ? processorType(raw, c.ids, c.shapes.unions) : declared.replace("ProbeEntity", "AppEntity");
        // DeleteIntent's `entities` mismatch names the element type.
        if (c.shapes.conformance.get(k) === "DeleteIntent" && name === "entities" && !type.startsWith("[")) type = `[${type}]`;
        push(c.shapes.members, k, { name, type, optional: optionals.get(k)?.has(name) ?? false });
      }
    } else if (d.kind === "entity") {
      for (const member of c.shapes.members.get(k) ?? []) {
        const raw = types.get(k)?.get(member.name);
        if (raw) member.type = processorType(raw, c.ids, c.shapes.unions);
      }
    }
  }
}

function claimUnions(c: CensusRun): void {
  for (const d of c.decls) {
    const mentioned = [...membersOf(c, key(d)).map((m) => m.type), c.shapes.returns.get(key(d)) ?? ""].join(" ");
    for (const name of c.shapes.unions.keys()) {
      if (!c.unionOwner.has(name) && new RegExp(`\\b${name}\\b`).test(mentioned)) c.unionOwner.set(name, d.domain);
    }
  }
}

/** A census type as the control probe's Swift: schema accessors and unions become probe types. */
function probeSwift(c: CensusRun, type: string): string {
  return type
    .replace(/\.([a-z]\w*)\.(\w+)/g, (whole, domain: string, name: string) => {
      const d = c.byAccessor.get(`.${domain}.${name}`);
      return d ? structName(d) : whole;
    })
    .replace(/\b[A-Z]\w*\b/g, (word) =>
      c.unionOwner.has(word) ? `U_${c.unionOwner.get(word)}_${word}` : word === "AppEntity" ? "ProbeEntity" : word);
}

function controlSource(c: CensusRun, unionCases: (name: string, cases: string[]) => string[] = (_, cases) => cases): Source {
  const swift = (t: string) => probeSwift(c, t);
  const parameter = (m: Member) => {
    const types = m.contentTypes ? `(supportedContentTypes: [${m.contentTypes.map((t) => `UTType("${t}")!`).join(", ")}])` : "";
    return `@Parameter${types} var ${m.name}: ${swift(m.type)}${m.optional ? "?" : ""}`;
  };
  return assemble([
    ...[...c.unionOwner].map(([name, domain]) => ({
      text: ["@UnionValue", `enum U_${domain}_${name} {`,
        ...unionCases(name, c.shapes.unions.get(name)!).map((t, i) => `    case v${i}(${swift(t)})`), "}"].join("\n") + "\n",
    })),
    ...c.decls.map((d) => {
      const k = key(d);
      if (d.kind === "intent") {
        const returns = c.shapes.returns.get(k);
        const extra = [...(stubFor(c, d)?.members ?? []), ...(c.shapes.statics.get(k) ?? [])];
        return { key: k, text: intentText(d, extra, membersOf(c, k).map(parameter), returns && swift(returns)) };
      }
      if (d.kind === "entity") {
        const properties = membersOf(c, k).map((m) => `var ${m.name}: ${swift(m.type)}${m.optional ? "?" : ""}`);
        return { key: k, text: entityText(d, c.shapes.conformance.get(k), properties, true) };
      }
      return { key: k, text: enumText(d, (c.shapes.cases.get(k) ?? []).slice().sort(byCode)) };
    }),
  ]);
}

/**
 * Pass 4: build the control until it stops surfacing requirements no earlier pass could reach,
 * such as the content types a file parameter must accept. Returns the errors it still has.
 */
function confirm(c: CensusRun): string[] {
  for (let round = 1; ; round++) {
    const source = controlSource(c);
    const result = build(c.dir, source, `control${round}`);
    if (!result.succeeded && !result.metadata.some((d) => d.kind === "error")) {
      throw new Error(`control${round}: build failed without metadata errors`);
    }
    let learned = false;
    const unconfirmed: string[] = [];
    c.shapes.warnings.clear();
    let lastWarning: { owner: string; index: number } | undefined;
    eachMetadata(source, result, `control${round}`, (owner, kind, message, finding) => {
      const member = finding?.kind === "contentTypes" ? membersOf(c, owner).find((p) => p.name === finding.name) : undefined;
      if (finding?.kind === "contentTypes" && member && !member.contentTypes) {
        member.contentTypes = finding.supertypes;
        learned = true;
      } else if (finding?.kind === "static" && STATIC_TYPES[finding.name] && !c.shapes.statics.has(owner)) {
        push(c.shapes.statics, owner, `static let ${finding.name}: ${STATIC_TYPES[finding.name]} = ${finding.value}`);
        learned = true;
      } else if (kind === "error") {
        unconfirmed.push(`${owner.split(".").join(" ")}: ${message}`);
      } else if (kind === "warning") {
        push(c.shapes.warnings, owner, message);
        lastWarning = { owner, index: c.shapes.warnings.get(owner)!.length - 1 };
      } else if (lastWarning?.owner === owner) {
        c.shapes.warnings.get(owner)![lastWarning.index] += `. Fix-it: \`${formatFixit(message, c.ids)}\``;
      } else return false;
      return true;
    });
    if (learned && round < 3) continue;
    if (unconfirmed.length === 0 && !result.succeeded) throw new Error(`control${round}: failed with no attributable error`);
    return unique(unconfirmed);
  }
}

const unionsNamedBy = (c: CensusRun, k: string) => {
  const mentioned = [...membersOf(c, k).map((m) => m.type), c.shapes.returns.get(k) ?? ""].join(" ");
  return [...c.unionOwner.keys()].filter((name) => new RegExp(`\\b${name}\\b`).test(mentioned));
};

/**
 * Pass 5: whether each union builds with only its first case, and with only its last. A third
 * build cuts it to one wrong case (an entity adopting no schema); a union that accepts that is not
 * checked at all, so the other two results say nothing about it. Unions are cut in groups where no
 * schema names two members of one group, so every rejection belongs to exactly one union.
 */
function singleCase(c: CensusRun): Map<string, SingleCase> {
  const groups: string[][] = [];
  for (const name of c.unionOwner.keys()) {
    const clash = (g: string[]) => c.decls.some((d) => {
      const named = unionsNamedBy(c, key(d));
      return named.includes(name) && g.some((other) => named.includes(other));
    });
    const group = groups.find((g) => !clash(g));
    if (group) group.push(name);
    else groups.push([name]);
  }
  const result = new Map<string, SingleCase>();
  for (const [index, group] of groups.entries()) {
    const rejectedBy = (label: string, cut: (cases: string[]) => string[]) => {
      const source = controlSource(c, (name, cases) => (group.includes(name) ? cut(cases) : cases));
      const built = build(c.dir, source, `${label}${index + 1}`);
      const rejected = new Set<string>();
      for (const d of built.metadata.filter((m) => m.kind === "error")) {
        const owner = diagnosticOwner(source, d);
        for (const name of owner ? unionsNamedBy(c, owner) : []) if (group.includes(name)) rejected.add(name);
      }
      return rejected;
    };
    const first = rejectedBy("union-first", (cases) => cases.slice(0, 1));
    const last = rejectedBy("union-last", (cases) => cases.slice(-1));
    const wrong = rejectedBy("union-wrong", () => ["AppEntity"]);
    for (const name of group) {
      result.set(name, !wrong.has(name) ? "unverified" : first.has(name) || last.has(name) ? "no" : "yes");
    }
  }
  return result;
}

/** The installed iphoneos SDK's schemas, or `undefined` without Xcode (CI on Linux). */
export function readInterface(): { decls: SchemaDecl[]; sdkVersion: string } | undefined {
  const sdk = spawnSync("xcrun", ["--sdk", "iphoneos", "--show-sdk-path"], { encoding: "utf8" });
  if (sdk.status !== 0) return undefined;
  const sdkVersion = run("xcrun", ["--sdk", "iphoneos", "--show-sdk-version"]);
  return { decls: parseSchemaInterface(fs.readFileSync(path.join(sdk.stdout.trim(), INTERFACE), "utf8")), sdkVersion };
}

export function runCensus(): Census {
  if (spawnSync("pgrep", ["-x", "xcodebuild"], { encoding: "utf8" }).stdout.trim() !== "") {
    throw new Error("another xcodebuild is running; let it finish (or kill it) before starting the census");
  }
  // The device SDK, not the simulator's: VisualIntelligence.framework ships only in iphoneos.
  const sdk = readInterface();
  if (!sdk) throw new Error("xcrun found no iphoneos SDK; the census needs Xcode");
  const { decls, sdkVersion } = sdk;
  const [xcodeLine, buildLine] = run("xcodebuild", ["-version"]).split("\n");
  const xcode = `${xcodeLine} (${buildLine.replace("Build version ", "")})`;
  const unclassified = unique(decls.map((d) => d.domain)).filter((d) => !DOMAIN_TIERS[d]);
  if (unclassified.length > 0) {
    throw new Error(`new schema domain(s) ${unclassified.join(", ")}: add each to DOMAIN_TIERS from Apple's domain documentation`);
  }

  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "app-schemas-"));
  fs.mkdirSync(path.join(dir, "Probe"));
  fs.writeFileSync(path.join(dir, "Probe/App.swift"), 'import SwiftUI\n@main struct P: App { var body: some Scene { WindowGroup { Text("p") } } }\n');
  fs.writeFileSync(path.join(dir, "project.yml"), [
    "name: Census", "targets:", "  Census:", "    type: application", "    platform: iOS",
    `    deploymentTarget: "${sdkVersion}"`, "    sources: [Probe]", "    settings:", "      base:",
    "        PRODUCT_BUNDLE_IDENTIFIER: com.example.census", "        GENERATE_INFOPLIST_FILE: YES",
    "        SWIFT_VERSION: 6.0", "        CODE_SIGNING_ALLOWED: NO", "",
  ].join("\n"));
  // xcodegen lists sources at generation time; a file created afterwards is never compiled.
  fs.writeFileSync(path.join(dir, "Probe/All.swift"), "");
  run("xcodegen", ["generate", "--quiet"], dir);
  console.log(`census of ${decls.length} schemas, ${xcode}, iphoneos ${sdkVersion}; probe in ${dir}`);

  const c: CensusRun = {
    dir,
    decls,
    ids: schemaIds(decls),
    byAccessor: new Map(decls.filter((d) => d.kind !== "intent").map((d) => [`.${d.domain}.${d.name}`, d])),
    shapes: {
      conformance: new Map(), missing: new Map(), members: new Map(), returns: new Map(),
      cases: new Map(), unions: new Map(), statics: new Map(), warnings: new Map(),
    },
    unionOwner: new Map(),
  };
  conformances(c);
  memberTypes(c, requiredMembers(c));
  claimUnions(c);
  const unconfirmed = confirm(c);
  const single = unconfirmed.length === 0 ? singleCase(c) : new Map<string, SingleCase>();

  const tierOrder = Object.keys(TIER_TEXT);
  const domainOrder = unique(decls.map((d) => d.domain))
    .sort((a, b) => tierOrder.indexOf(DOMAIN_TIERS[a]) - tierOrder.indexOf(DOMAIN_TIERS[b]) || byCode(a, b));
  const byName = <T extends { name: string }>(list: T[]) => list.sort((a, b) => byCode(a.name, b.name));
  const domains = domainOrder.map((domain): DomainCensus => {
    const of = (kind: Kind) => decls.filter((d) => d.domain === domain && d.kind === kind);
    const base = (d: SchemaDecl) => ({ name: d.name, available: d.available, deprecated: d.deprecated });
    const unions = [...c.unionOwner].filter(([, owner]) => owner === domain).map(([name]) => name).sort(byCode);
    return {
      name: domain,
      tier: DOMAIN_TIERS[domain],
      intents: byName(of("intent").map((d) => ({
        ...base(d), conformance: c.shapes.conformance.get(key(d)), parameters: membersOf(c, key(d)),
        returns: c.shapes.returns.get(key(d)), statics: c.shapes.statics.get(key(d)), warnings: c.shapes.warnings.get(key(d)),
      }))),
      entities: byName(of("entity").map((d) => ({
        ...base(d), conformance: c.shapes.conformance.get(key(d)), properties: membersOf(c, key(d)),
      }))),
      enums: byName(of("enum").map((d) => ({ ...base(d), cases: (c.shapes.cases.get(key(d)) ?? []).slice().sort(byCode) }))),
      unions: Object.fromEntries(unions.map((name) => [name, c.shapes.unions.get(name)!])),
      singleCase: Object.fromEntries(unions.map((name) => [name, single.get(name) ?? "unverified"])),
    };
  });
  fs.rmSync(dir, { recursive: true, force: true });
  return { xcode, sdk: `iphoneos ${sdkVersion}`, domains, unconfirmed };
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === import.meta.filename) {
  const args = process.argv.slice(2);
  const relative = (file: string) => path.relative(ROOT, file);
  if (args.length > 1 || (args.length === 1 && !["census", "--check"].includes(args[0]))) {
    console.error("usage: node scripts/app-schemas.ts [census | --check]");
    process.exit(2);
  }
  if (args[0] === "census") {
    const census = runCensus();
    fs.writeFileSync(CENSUS_FILE, `${JSON.stringify(census, null, 2)}\n`);
    console.log(`wrote ${relative(CENSUS_FILE)}; ${census.unconfirmed.length} unconfirmed`);
  }
  const census: Census = JSON.parse(fs.readFileSync(CENSUS_FILE, "utf8"));
  const reference = fs.readFileSync(REFERENCE_FILE, "utf8");
  const next = replaceGeneratedSection(reference, renderSchemaReference(census));
  if (next === undefined) {
    console.error(`✗ ${relative(REFERENCE_FILE)} lacks the generated-section markers`);
    process.exit(1);
  }
  if (args[0] === "--check") {
    if (next !== reference) {
      console.error(`✗ ${relative(REFERENCE_FILE)} is stale; run node scripts/app-schemas.ts`);
      process.exit(1);
    }
    let installed: ReturnType<typeof readInterface>;
    try {
      installed = readInterface();
    } catch (error) {
      console.error(`✗ the installed SDK's interface no longer parses (${(error as Error).message}); fix the parser, then run node scripts/app-schemas.ts census`);
      process.exit(1);
    }
    if (installed) {
      const drift = interfaceDrift(installed.decls, census);
      if (drift.length > 0) {
        console.error(`✗ the installed iphoneos ${installed.sdkVersion} SDK and ${relative(CENSUS_FILE)} (${census.sdk}) disagree; run node scripts/app-schemas.ts census`);
        for (const line of drift.slice(0, 20)) console.error(`  ${line}`);
        process.exit(1);
      }
    }
    console.log(`✓ schema reference matches the census${installed ? ` and the installed iphoneos ${installed.sdkVersion} SDK` : ""}`);
  } else if (next !== reference) {
    fs.writeFileSync(REFERENCE_FILE, next);
    console.log(`updated ${relative(REFERENCE_FILE)}`);
  }
}
