/** Orders availability tags by release: `OS27` > `iOS 26.2+; …` > `iOS 18+, …`. */
export function availabilityRank(available: string): number {
  const m = /^OS(\d+)/.exec(available) ?? /(\d+(?:\.\d+)?)/.exec(available);
  return m ? Number(m[1]) : 0;
}

function mostCommon(values: string[]): string {
  const counts = new Map<string, number>();
  for (const v of values) counts.set(v, (counts.get(v) ?? 0) + 1);
  return [...counts].sort((a, b) => b[1] - a[1])[0][0];
}

const orList = (items: string[]) =>
  items.length < 2 ? items.join("") : `${items.slice(0, -1).join(", ")} or ${items[items.length - 1]}`;

function members(list: Member[]): string {
  if (list.length === 0) return "—";
  const typed = `\`${list.map((m) => `${m.name}: ${m.type}${m.optional ? "?" : ""}`).join(", ")}\``;
  const constraints = list
    .filter((m) => m.contentTypes)
    .map((m) => `; \`${m.name}\` content types: ${orList(m.contentTypes!)}`);
  return typed + constraints.join("");
}

const namedTypes = (s: Schema) =>
  [...("parameters" in s ? s.parameters : "properties" in s ? s.properties : []).map((m) => m.type), ("returns" in s && s.returns) || ""];

export function renderSchemaReference(census: Census): string {
  const out: string[] = [];
  const confirmed = census.unconfirmed.length === 0
    ? "A control build adopting every schema exactly as listed produced no errors."
    : "A control build adopting every schema exactly as listed still produced the errors below; those rows are incomplete.";
  out.push(`Census: ${census.xcode}, ${census.sdk} SDK. ${confirmed}`, "");
  if (census.unconfirmed.length > 0) out.push(...census.unconfirmed.map((u) => `- ${u}`), "");

  const availability = new Map<string, string>();
  for (const d of census.domains) for (const s of [...d.entities, ...d.enums]) availability.set(`.${d.name}.${s.name}`, s.available);
  const unions = new Map(census.domains.flatMap((d) => Object.entries(d.unions)));
  // A row is usable only where every type it names exists: iOS 18 Photos intents take the OS27 `.photos.asset`.
  const effective = (s: Schema): string => {
    const named = namedTypes(s).flatMap((t) => [t, ...[...t.matchAll(/\b[A-Z]\w*\b/g)].flatMap((u) => unions.get(u[0]) ?? [])]);
    const refs = named.flatMap((t) => [...t.matchAll(/\.[a-z]\w*\.\w+/g)].map((m) => availability.get(m[0]) ?? s.available));
    return [s.available, ...refs].reduce((a, b) => (availabilityRank(b) > availabilityRank(a) ? b : a));
  };

  for (const domain of census.domains) {
    const all = [...domain.intents, ...domain.entities, ...domain.enums];
    const platforms = mostCommon(all.map(effective));
    const label = (s: Schema) => {
      let cell = `\`${s.name}\``;
      if ("conformance" in s && s.conformance) cell += ` (${s.conformance})`;
      const available = effective(s);
      if (available !== platforms) cell += available.startsWith("OS") ? ` ${available.replace(/^OS\d+/, "`$&`")}` : ` (${available})`;
      if (s.deprecated) cell += `, deprecated in ${s.deprecated.replace(/(\.[a-z]\w*\.\w+)/g, "`$1`")}`;
      return cell;
    };
    out.push(`## ${upperFirst(domain.name)}`, "", `**Tier**: ${TIER_TEXT[domain.tier]}. **Platforms**: ${platforms}`, "");
    if (domain.intents.length > 0) {
      out.push("| Intent | Required parameters | Returns |", "|---|---|---|");
      for (const i of domain.intents) {
        const needs = (i.statics ?? []).map((st) => `needs \`${st}\``);
        const cell = i.parameters.length === 0 && needs.length > 0 ? needs.join("; ") : [members(i.parameters), ...needs].join("; ");
        out.push(`| ${label(i)} | ${cell} | ${i.returns ? `\`${i.returns}\`` : "—"} |`);
      }
      out.push("");
    }
    if (domain.entities.length > 0) {
      out.push("| Entity | Required properties |", "|---|---|");
      for (const e of domain.entities) out.push(`| ${label(e)} | ${members(e.properties)} |`);
      out.push("");
    }
    const withCases = domain.enums.filter((e) => e.cases.length > 0);
    const caseless = domain.enums.filter((e) => e.cases.length === 0);
    if (withCases.length > 0) {
      out.push("| Enum | Required cases |", "|---|---|");
      for (const e of withCases) out.push(`| ${label(e)} | \`${e.cases.join(", ")}\` |`);
      out.push("");
    }
    if (caseless.length > 0) out.push(`Enums with no required cases: ${caseless.map(label).join(", ")}`, "");
    const domainUnions = Object.entries(domain.unions);
    if (domainUnions.length > 0) {
      out.push("| Union (`@UnionValue`) | Cases | Builds with only its first case, and with only its last |", "|---|---|---|");
      for (const [name, cases] of domainUnions) out.push(`| \`${name}\` | \`${cases.join(", ")}\` | ${domain.singleCase[name]} |`);
      out.push("");
    }
    const warned = domain.intents.filter((i) => i.warnings?.length);
    if (warned.length > 0) {
      out.push("Build warnings (the build still succeeds):", "");
      for (const i of warned) for (const w of i.warnings!) out.push(`- \`${i.name}\`: ${w}`);
      out.push("");
    }
  }
  return out.join("\n");
}

export function replaceGeneratedSection(
  markdown: string,
  section: string,
  start = GENERATED_START,
  end = GENERATED_END,
): string | undefined {
  const a = markdown.indexOf(start);
  const b = a < 0 ? -1 : markdown.indexOf(end, a);
  if (a < 0 || b < 0) return undefined;
  return `${markdown.slice(0, a + start.length)}\n${section}${markdown.slice(b)}`;
}

const signature = (domain: string, kind: Kind, s: { name: string; available: string; deprecated?: string }) =>
  `${domain}.${kind}.${s.name} ${s.available}${s.deprecated ? `, deprecated ${s.deprecated}` : ""}`;

/** Schemas the installed SDK and the census disagree on: `+` only in the SDK, `-` only in the census. */
export function interfaceDrift(decls: SchemaDecl[], census: Census): string[] {
  const sdk = new Set(decls.map((d) => signature(d.domain, d.kind, d)));
  const recorded = new Set(census.domains.flatMap((d) => [
    ...d.intents.map((s) => signature(d.name, "intent", s)),
    ...d.entities.map((s) => signature(d.name, "entity", s)),
    ...d.enums.map((s) => signature(d.name, "enum", s)),
  ]));
  return [
    ...[...sdk].filter((s) => !recorded.has(s)).map((s) => `+ ${s}`),
    ...[...recorded].filter((s) => !sdk.has(s)).map((s) => `- ${s}`),
  ].sort(byCode);
}

