export type Source = { text: string; owners: Array<{ line: number; key: string }> };

/** One probe file, recording the line each keyed declaration starts on so errors can be attributed. */
export function assemble(parts: Array<{ key?: string; text: string }>): Source {
  // Module-qualified census types (GeoToolbox.PlaceDescriptor) need their module imported.
  const modules = unique(parts.flatMap((p) => [...p.text.matchAll(/\b([A-Z]\w+)\.[A-Z]\w+/g)].map((m) => m[1])))
    .filter((m) => !["Calendar", "Swift", "Foundation", "AppIntents"].includes(m) && !/^[EINU]_/.test(m))
    .sort(byCode);
  const header = ["AppIntents", "Foundation", "UniformTypeIdentifiers", ...modules].map((m) => `import ${m}\n`).join("") + "\n" +
    "func probeValue<T>() -> T { fatalError() }\n\n" +
    "struct ProbeEntity: AppEntity {\n    var id: String\n" +
    '    static let typeDisplayRepresentation: TypeDisplayRepresentation = "p"\n' +
    '    var displayRepresentation: DisplayRepresentation { "p" }\n' +
    "    static let defaultQuery = ProbeEntityQuery()\n}\n" +
    "struct ProbeEntityQuery: EntityQuery { func entities(for identifiers: [String]) async throws -> [ProbeEntity] { [] } }\n";
  let text = header;
  const owners: Source["owners"] = [];
  for (const part of parts) {
    text += "\n";
    if (part.key) owners.push({ line: text.split("\n").length, key: part.key });
    text += part.text;
  }
  return { text, owners };
}

/** The keyed declaration a 1-based line falls in. */
export function ownerOf(source: Source, line: number): string | undefined {
  let found: string | undefined;
  for (const o of source.owners) if (o.line <= line) found = o.key;
  return found;
}

/** Types of static intent members the processor can demand by value (`requires 'supportedModes = .foreground'`). */
const STATIC_TYPES: Record<string, string> = { supportedModes: "IntentModes" };

const STUBS: Record<string, { members: string[]; parameters: Member[] }> = {
  OpenIntent: { members: [], parameters: [{ name: "target", type: "ProbeEntity", optional: false }] },
  DeleteIntent: { members: [], parameters: [{ name: "entities", type: "[ProbeEntity]", optional: false }] },
  ShowInAppSearchResultsIntent: {
    members: ["static let searchScopes: [StringSearchScope] = [.general]"],
    parameters: [{ name: "criteria", type: "StringSearchCriteria", optional: false }],
  },
};

function entityText(d: SchemaDecl, conformance: string | undefined, properties: string[], control: boolean): string {
  const name = structName(d);
  const idType = conformance === "FileEntity" ? "FileEntityIdentifier" : "String";
  const lines = [`@AppEntity(schema: .${d.domain}.${d.name})`, `struct ${name}: AppEntity {`, `    var id: ${idType}`];
  if (conformance === "FileEntity") lines.push("    static let supportedContentTypes: [UTType] = [.data]");
  lines.push(...properties.map((p) => `    ${p}`));
  lines.push('    var displayRepresentation: DisplayRepresentation { "x" }', `    static let defaultQuery = ${name}Query()`, "}");
  const queryFns = [`    func entities(for identifiers: [${idType}]) async throws -> [${name}] { [] }`];
  let protocol = "EntityQuery";
  if (conformance === "UniqueAppEntity") {
    protocol = "UniqueAppEntityQuery";
    queryFns.push(`    func allEntities() async throws -> [${name}] { [] }`, `    func uniqueEntity() async throws -> ${name} { probeValue() }`);
  } else if (control) {
    protocol = "EntityStringQuery";
    queryFns.push(`    func entities(matching string: String) async throws -> [${name}] { [] }`);
  }
  lines.push(`struct ${name}Query: ${protocol} {`, ...queryFns, "}");
  return lines.join("\n") + "\n";
}

function enumText(d: SchemaDecl, cases: string[]): string {
  const all = cases.length > 0 ? cases : ["placeholderCase"];
  return [
    `@AppEnum(schema: .${d.domain}.${d.name})`,
    `enum ${structName(d)}: String {`,
    ...all.map((c) => `    case ${caseName(c)}`),
    `    static let caseDisplayRepresentations: [Self: DisplayRepresentation] = [${all.map((c) => `.${c}: "x"`).join(", ")}]`,
    "}",
  ].join("\n") + "\n";
}

function intentText(d: SchemaDecl, extra: string[], parameters: string[], returns: string | undefined): string {
  const result = returns
    ? `some IntentResult & ReturnsValue<${returns}> { .result(value: probeValue() as ${returns}) }`
    : "some IntentResult { .result() }";
  return [
    `@AppIntent(schema: .${d.domain}.${d.name})`,
    `struct ${structName(d)}: AppIntent {`,
    ...extra.map((e) => `    ${e}`),
    ...parameters.map((p) => `    ${p}`),
    `    func perform() async throws -> ${result}`,
    "}",
  ].join("\n") + "\n";
}

