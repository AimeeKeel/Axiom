const BLOCK = /^extension AppIntents::AppSchema\.AppIntents::(\w+?)(Intent|Entity|Enum) \{$/;
const ACCESSOR = /\bpublic var (\w+): some AppIntents::AppSchema(?:Intent|Entity|Enum) \{$/;
const SCHEMA_ID = /AppSchema\.(?:Intent|Entity|Enum)\("([^"]+)"\)/;
const DEPRECATION = /^@available\(\w+, deprecated: ([\d.]+), message: "([^"]+)"\)$/;

const lowerFirst = (s: string) => s[0].toLowerCase() + s.slice(1);
const upperFirst = (s: string) => s[0].toUpperCase() + s.slice(1);
const unique = <T>(items: T[]) => [...new Set(items)];
const byCode = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * An `@available` stack as one tag; later clauses for a platform override earlier ones. watchOS and
 * tvOS are unavailable for every schema, so they go unsaid.
 */
export function normalizeAvailability(clauses: string[]): string {
  const introduced = new Map<string, string>();
  const unavailable = new Set<string>();
  for (const clause of clauses) {
    const parts = clause.split(",").map((p) => p.trim());
    const excluded = /^(\w+)$/.exec(parts[0]);
    if (parts.length === 2 && parts[1] === "unavailable" && excluded && parts[0] !== "anyAppleOS") {
      introduced.delete(parts[0]);
      if (parts[0] !== "watchOS" && parts[0] !== "tvOS") unavailable.add(parts[0]);
      continue;
    }
    for (const part of parts) {
      if (part === "*") continue;
      const m = /^(\w+) (\d+(?:\.\d+)*)$/.exec(part);
      if (!m) throw new Error(`unrecognized @available clause: ${clause}`);
      introduced.set(m[1], m[2].replace(/\.0$/, ""));
      unavailable.delete(m[1]);
    }
  }
  const intro = [...introduced]
    .map(([p, v]) => (p !== "anyAppleOS" ? `${p} ${v}+` : v.includes(".") ? `anyAppleOS ${v}+` : `OS${v}`))
    .join(", ");
  return unavailable.size === 0 ? intro : `${intro}; not ${[...unavailable].join("/")}`;
}

/** Every schema accessor; throws when the interface holds a schema id no accessor accounted for. */
export function parseSchemaInterface(text: string): SchemaDecl[] {
  const lines = text.split("\n");
  const decls: SchemaDecl[] = [];
  for (let i = 0; i < lines.length; i++) {
    const block = BLOCK.exec(lines[i]);
    if (!block) continue;
    const clauses: string[] = [];
    for (let j = i - 1; j >= 0 && lines[j].startsWith("@available("); j--) {
      clauses.unshift(lines[j].slice("@available(".length, -1));
    }
    const domain = lowerFirst(block[1]);
    const kind = block[2].toLowerCase() as Kind;
    for (i++; i < lines.length && lines[i] !== "}"; i++) {
      const accessor = ACCESSOR.exec(lines[i]);
      if (!accessor) continue;
      const name = accessor[1];
      const id = SCHEMA_ID.exec(lines[i + 2] ?? "");
      if (!id) throw new Error(`schema accessor ${domain}.${name}: no AppSchema id two lines below line ${i + 1}`);
      const own = [...lines[i].slice(0, accessor.index).matchAll(/@available\(([^)]*)\)/g)].map((m) => m[1]);
      let deprecated: string | undefined;
      for (let j = i - 1; lines[j].trim().startsWith("@available("); j--) {
        const attribute = lines[j].trim();
        if (!attribute.includes("deprecated")) {
          own.unshift(attribute.slice("@available(".length, -1));
          continue;
        }
        const d = DEPRECATION.exec(attribute);
        if (!d) throw new Error(`schema accessor ${domain}.${name}: unrecognized deprecation ${attribute}; extend DEPRECATION`);
        const replacement = /^Use (.+) instead$/.exec(d[2]);
        deprecated = `${d[1].replace(/\.0$/, "")}; ${replacement ? `use ${replacement[1]}` : d[2]}`;
      }
      const decl: SchemaDecl = { domain, kind, name, id: id[1], available: normalizeAvailability([...clauses, ...own]) };
      if (deprecated) decl.deprecated = deprecated;
      decls.push(decl);
    }
  }
  // Domain accessors carry lowercase ids (`AppSchema.Intent("notes")`); every capitalized id is a schema.
  const parsed = new Set(decls.map((d) => d.id));
  const stray = unique([...text.matchAll(/AppSchema\.(?:Intent|Entity|Enum)\("([A-Z][^"]*)"\)/g)].map((m) => m[1]))
    .filter((id) => !parsed.has(id));
  if (stray.length > 0) throw new Error(`schema ids no accessor accounted for: ${stray.join(", ")}; extend BLOCK or ACCESSOR`);
  return decls;
}

/** Internal schema id (`NoteEntity`) to the accessor developers write (`.notes.note`). */
export function schemaIds(decls: SchemaDecl[]): Map<string, string> {
  return new Map(decls.filter((d) => d.kind !== "intent").map((d) => [d.id, `.${d.domain}.${d.name}`]));
}

const PROCESSOR_NAMES: Record<string, string> = {
  File: "IntentFile",
  Person: "IntentPerson",
  RecurrenceRule: "Calendar.RecurrenceRule",
  LinkMetadata: "LinkPresentation.LinkMetadata",
};

function splitTopLevel(text: string, separator: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if ("<([".includes(text[i])) depth++;
    else if (">)]".includes(text[i])) depth--;
    else if (depth === 0 && text.startsWith(separator, i)) {
      parts.push(text.slice(start, i));
      start = i + separator.length;
    }
  }
  parts.push(text.slice(start));
  return parts;
}

/** A type as appintentsmetadataprocessor prints it, in the spelling a developer writes. Records unions it meets. */
export function processorType(raw: string, ids: Map<string, string>, unions: Map<string, string[]>): string {
  let m: RegExpExecArray | null;
  if ((m = /^(\w+)Cases:\((.*)\)$/.exec(raw))) {
    const cases = splitTopLevel(m[2], " | ").map((c) => processorType(c, ids, unions));
    const known = unions.get(m[1]);
    if (known && known.join("|") !== cases.join("|")) {
      throw new Error(`union ${m[1]} appears with two case lists: ${known.join(", ")} and ${cases.join(", ")}`);
    }
    unions.set(m[1], cases);
    return m[1];
  }
  if ((m = /^Array<(.*)>$/.exec(raw))) return `[${processorType(m[1], ids, unions)}]`;
  if ((m = /^Set<(.*)>$/.exec(raw))) return `Set<${processorType(m[1], ids, unions)}>`;
  if ((m = /^Schema<(\w+)>$/.exec(raw))) return ids.get(m[1]) ?? m[1];
  if ((m = /^SystemEntity<.*\.(\w+)\.(\w+)Entity>$/.exec(raw))) return `${m[1]}.${m[2]}`;
  if ((m = /^Codable<Swift\.(\w+)>$/.exec(raw))) return m[1];
  return PROCESSOR_NAMES[raw] ?? ids.get(raw) ?? raw;
}

/** A fix-it's Swift type, placeholders (`<#FolderEntity#>`) resolved to schema accessors. */
export function fixitType(raw: string, ids: Map<string, string>): { type: string; optional: boolean } {
  const optional = raw.endsWith("?");
  const type = (optional ? raw.slice(0, -1) : raw).replace(/<#(\w+)#>/g, (_, id: string) => ids.get(id) ?? id);
  return { type, optional };
}

/** A multi-line fix-it, as the log escapes it, on one line with schema accessors for internal ids. */
export function formatFixit(raw: string, ids: Map<string, string>): string {
  return raw
    .replace(/\\n/g, " ")
    .replace(/\{\s*<#code#>\s*\}/g, "")
    .replace(/\b\w+\b/g, (word) => ids.get(word) ?? word)
    .replace(/\s+/g, " ")
    .trim();
}

const METADATA_ERROR = /\/Probe\/All\.swift:(\d+): (error|warning): (.*)$/;
const METADATA_FIXIT = /\/Probe\/All\.swift:(\d+):\d+: fixit: (.*)$/;
const PROCESSOR_ERROR = /^error: (.*'\w+\.\w+'.*)$/;
const SWIFT_ERROR = /(?:\/Probe\/\w+\.swift:\d+:\d+|^macro expansion @\w+:\d+:\d+): error: (.*)$/;

export function parseDiagnostics(log: string): Diagnostics {
  const metadata: Diagnostics["metadata"] = [];
  const seen = new Set<string>();
  const swift: string[] = [];
  for (const line of log.split("\n")) {
    const error = METADATA_ERROR.exec(line);
    const fixit = METADATA_FIXIT.exec(line);
    const located = PROCESSOR_ERROR.exec(line);
    const entry = error
      ? { line: Number(error[1]), kind: error[2] as MetadataKind, message: error[3] }
      : fixit
        ? { line: Number(fixit[1]), kind: "fixit" as MetadataKind, message: fixit[2] }
        : located
          ? { line: 0, kind: "error" as MetadataKind, message: located[1] }
          : undefined;
    if (entry) {
      const k = `${entry.line}\0${entry.kind}\0${entry.message}`;
      if (!seen.has(k)) metadata.push(entry);
      seen.add(k);
      continue;
    }
    const sw = SWIFT_ERROR.exec(line);
    if (sw) swift.push(sw[1]);
  }
  return { metadata, swift: unique(swift) };
}

export type Finding =
  | { kind: "missing"; name: string }
  | { kind: "case"; name: string }
  | { kind: "returns"; type: string }
  | { kind: "type"; name: string; type: string }
  | { kind: "optionality"; name: string; optional: boolean }
  | { kind: "contentTypes"; name: string; supertypes: string[] }
  | { kind: "static"; name: string; value: string }
  | { kind: "noShape" };

const FINDINGS: Array<[RegExp, (m: RegExpExecArray) => Finding]> = [
  [/^Missing required (?:parameter|property) '(\w+)' from AppSchema\w+ '[\w.]+'$/, (m) => ({ kind: "missing", name: m[1] })],
  [/ requires enum case '(\w+)'$/, (m) => ({ kind: "case", name: m[1] })],
  [/ requires that 'perform\(\)' include a 'ReturnsValue<(.+)>'$/, (m) => ({ kind: "returns", type: m[1] })],
  [
    /^(?:Parameter|Property) '(\w+)' (?:type )?does not match required AppSchema\w+ (?:type|parameter of|property of|property type) '(.+)'$/,
    (m) => ({ kind: "type", name: m[1], type: m[2] }),
  ],
  [/^Required AppSchema\w+ (?:parameter|property) '(\w+)' must (not )?be optional$/, (m) => ({ kind: "optionality", name: m[1], optional: !m[2] })],
  [
    /^The 'supportedTypeIdentifiers' argument of parameter '(\w+)' must specify at least one UTType subtype of the following supertypes: (.+)$/,
    (m) => ({ kind: "contentTypes", name: m[1], supertypes: [...m[2].matchAll(/'([^']+)'/g)].map((t) => t[1]) }),
  ],
  [/^\w+ '[\w.]+' requires '(\w+) = (.+)'$/, (m) => ({ kind: "static", name: m[1], value: m[2] })],
  // OpenIntent objecting to another non-optional parameter, which pass 3 reports as "must be optional" anyway.
  [/^'\w+' must have '\w+' as the only required parameter$/, () => ({ kind: "noShape" })],
];

/** What one processor error says about a schema's shape; `undefined` for wording the census has not met. */
export function classifyMetadata(message: string): Finding | undefined {
  for (const [pattern, finding] of FINDINGS) {
    const m = pattern.exec(message);
    if (m) return finding(m);
  }
  return undefined;
}

